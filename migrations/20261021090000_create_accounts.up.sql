-- NAS accounts (docs/login.md): one per console, made by `acctcreate`, the
-- client's registration. The console keeps the userid and logs in with it.
-- Nothing identifies the console itself: the port sends the same MAC, serial
-- and Wii number from every install.
CREATE TABLE accounts (
    -- Random. DWC keeps 43 bits of it.
    user_id       BIGINT      PRIMARY KEY CHECK (user_id BETWEEN 0 AND 8796093022207),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ
);

-- GameSpy profiles: one per account and game (`gsbrcd`: the game code and a
-- Mii slot's id), made at its first GPCM login. The profile id is the
-- player's identity everywhere else, e.g. `scores.profile_id`.
CREATE TABLE profiles (
    profile_id    INTEGER     GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000) PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES accounts,
    gsbrcd        TEXT        NOT NULL CHECK (length(gsbrcd) BETWEEN 4 AND 16),
    -- base32(user_id) || gsbrcd, as GameSpy and WiiLink name profiles.
    unique_nick   TEXT        NOT NULL UNIQUE,
    -- Set by the client (`updatepro`): DWC keeps its own login id in `lastname`.
    firstname     TEXT        NOT NULL DEFAULT '',
    lastname      TEXT        NOT NULL DEFAULT '',
    -- The Mii name of the last NAS login.
    ingamesn      TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_ip       TEXT,
    UNIQUE (user_id, gsbrcd)
);
